  HAL_GPIO_WritePin(GPIOB, DO1_Pin|DO2_Pin|DO4_Pin|DO3_Pin, GPIO_PIN_RESET);

  /*Configure GPIO pins : DI4_Pin DI3_Pin LSM_INT2_Pin */
